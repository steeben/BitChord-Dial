package com.music.bitchord.data

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class MusicVideoTermsTest {
    @Test fun titlesThatNameThemselvesAreTaken() {
        listOf(
            "Third Eye Blind - Semi-Charmed Life (Official Music Video)",
            "Semi-Charmed Life [Official HD Video]",
            "Artist - Song (Official Lyric Video)",
            "Artist - Song (Lyrics)",
            "Artist - Song (Official Visualizer)",
            "Artist – Song | Visualiser",
            "Artist 'Song' M/V",
            "Artist - Song (Video Oficial)",
            "Artist - Song (Clip officiel)",
            "Artist - Song (Animated Video)",
        ).forEach { assertTrue(MusicVideoTerms.inTitle(it), it) }
    }

    @Test fun plainTitlesAreNot() {
        listOf("Semi-Charmed Life", "Song (Official Audio)", "Song (Live at Wembley)", "Song - Topic", "", null)
            .forEach { assertFalse(MusicVideoTerms.inTitle(it), it.toString()) }
    }

    @Test fun descriptionNeedsAPhraseNotJustLyrics() {
        assertTrue(MusicVideoTerms.inDescription("Music video by Third Eye Blind performing Semi-Charmed Life."))
        assertTrue(MusicVideoTerms.inDescription("Watch the official visualizer for Song.\nStream: ..."))
        assertFalse(MusicVideoTerms.inDescription("Provided to YouTube by Label\n\nSong · Artist\n\nAuto-generated by YouTube."))
        assertFalse(MusicVideoTerms.inDescription("Lyrics:\nI want something else"))
        assertFalse(MusicVideoTerms.inDescription(null))
    }

    @Test fun descriptionIsReadOffTheWatchPage() {
        val html = """<script>var ytInitialPlayerResponse = {"videoDetails":{"videoId":"abcdefghijk",
            "shortDescription":"Official music video for Song"}};</script>"""
        assertEquals("Official music video for Song", SongInfoParser.description(html, "abcdefghijk"))
    }
}
